def main():
    with open(BASE, encoding="utf-8") as f:
        bank = json.load(f)

    # Видалити старий розділ, якщо існує
    bank["sections"] = [s for s in bank["sections"] if s["id"] != SECTION["id"]]
    bank["sections"].append(SECTION)

    # Перерахувати total
    bank["total"] = sum(s["count"] for s in bank["sections"])

    with open(BASE, "w", encoding="utf-8") as f:
        json.dump(bank, f, ensure_ascii=False, indent=2)

    print(f"Додано розділ «{SECTION['title']}» ({SECTION['count']} питань)")
    print(
        f"Загальна кількість питань: {bank['total']}, розділів: {len(bank['sections'])}"
    )


if __name__ == "__main__":
    main()
