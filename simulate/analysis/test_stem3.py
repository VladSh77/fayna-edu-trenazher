NEG_RE = re.compile("|".join(NEG_PATTERNS), re.IGNORECASE)


def is_neg_question(q):
    return bool(NEG_RE.search(q))


def get_article(q):
    ref = (q.get("explain") or {}).get("ref", "")
    if not ref:
        return None
    if ref in law_cache:
        return law_cache[ref]
    try:
        fname = S.legislation_file(ref)
        if not fname:
            law_cache[ref] = None
            return None
        p = S.LAWS_DIR / fname
        if not p.exists():
            law_cache[ref] = None
            return None
        html = p.read_text(encoding="utf-8", errors="replace")
        art = S.extract_article_by_ref(html, ref)
        law_cache[ref] = art
        return art
    except Exception:
        law_cache[ref] = None
        return None


def stem_ratio(correct, article_text):
    if not article_text:
        return 0.0
    cw = S.significant_words(correct)
    if not cw:
        return 0.0
    aw = S.significant_words(article_text)
    if not aw:
        return 0.0
    hit = 0
    for w in cw:
        base = w[:MIN_STEM]
        if any(a.startswith(base) for a in aw):
            hit += 1
    return hit / len(cw)


