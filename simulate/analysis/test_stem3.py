    total_fixed = 0
    neg_fixed = 0
    pos_fixed = 0
    neg_examples = []
    pos_examples = []
    for sec in bank.get("sections", []):
        for q in sec.get("questions", []):
            sid = q.get("_section_id", "")
            if sid == "krainoznavstvo-polsha":
                continue
            correct = q.get("correct") or ""
            if not correct:
                continue
            art = get_article(q)
            if not art:
                continue
            art_text = art[1] if isinstance(art, tuple) else str(art)
            lex = S.answer_matches_article(correct, art_text)
            if isinstance(lex, tuple):
                lex = lex[1]
            if lex >= THRESHOLD:
                continue
            stem = stem_ratio(correct, art_text)
            if stem < THRESHOLD:
                continue
            total_fixed += 1
            qid = q.get("id") or q.get("question") or ""
            if is_neg_question(str(q.get("question", ""))):
                neg_fixed += 1
                if len(neg_examples) < 10:
                    neg_examples.append((qid, q.get("question"), correct))
            else:
                pos_fixed += 1
                if len(pos_examples) < 10:
                    pos_examples.append((qid, q.get("question"), correct))
