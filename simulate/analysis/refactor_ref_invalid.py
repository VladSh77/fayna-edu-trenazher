def main():
    with open(BANK) as f:
        bank = json.load(f)

    # Індексуємо питання за id
    by_id = {}
    for sec in bank["sections"]:
        for q in sec.get("questions", []):
            by_id[q["id"]] = q

    applied = []
    not_found = []

    # --- FIXES: заміна ref ---
    for qid, old, new in FIXES:
        q = by_id.get(qid)
        if q is None:
            not_found.append((qid, "question id not found", old, ""))
            continue
        ref = q.get("explain", {}).get("ref", "")
        if old not in ref:
            not_found.append((qid, "ref value mismatch", old, ref))
            continue
        q["explain"]["ref"] = new
        applied.append((qid, old, new))

    # --- KRAJ_FIXES: перекласифікація як KRAJOZNAWSTWO ---
    for qid, old in KRAJ_FIXES:
        q = by_id.get(qid)
        if q is None:
            not_found.append((qid, "question id not found", old, ""))
            continue
        ref = q.get("explain", {}).get("ref", "")
        if old not in ref:
            not_found.append((qid, "ref value mismatch", old, ref))
            continue
        q["explain"]["ref"] = KRAJ_EU_MARKER
        applied.append((qid, old, KRAJ_EU_MARKER))

    with open(BANK, "w") as f:
        json.dump(bank, f, ensure_ascii=False, indent=2)

    print("=== APPLIED REF FIXES ===")
    for a in applied:
        print(f"  [{a[0]}] '{a[1]}' -> '{a[2]}'")
    print(f"\nTotal applied: {len(applied)}")
    if not_found:
        print("\n=== NOT FOUND / MISMATCH ===")
        for nf in not_found:
            print(f"  {nf}")


if __name__ == "__main__":
    main()
